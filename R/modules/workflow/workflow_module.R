# Cardinal NEST - workflow module
# Pipeline save/load (JSON), headless R script export, batch preprocessing.

library(shiny)

# Normalize a workflow spec; each step is list(type = <key>, args = <list>).
validate_workflow_specs <- function(specs) {
  if (is.null(specs)) return(list())
  if (!is.list(specs)) {
    stop("Workflow must be a list of steps.", call. = FALSE)
  }
  lapply(seq_along(specs), function(i) {
    s <- specs[[i]]
    if (!is.list(s) || is.null(s$type) || !is.character(s$type) ||
        length(s$type) != 1L || is.na(s$type)) {
      stop(sprintf("Step %d: missing or invalid 'type'.", i), call. = FALSE)
    }
    if (is.null(preproc_step_defs[[s$type]])) {
      stop(sprintf("Step %d: unknown preprocessing step '%s'.", i, s$type),
           call. = FALSE)
    }
    args <- s$args
    if (is.null(args)) args <- list()
    if (!is.list(args)) {
      stop(sprintf("Step %d (%s): 'args' must be a named list.",
                   i, s$type), call. = FALSE)
    }
    list(type = s$type, args = args)
  })
}

# Serialize to a JSON string with a versioned envelope.
serialize_workflow <- function(specs, name = NULL) {
  specs <- validate_workflow_specs(specs)
  steps <- lapply(specs, function(s) list(type = s$type, args = as.list(s$args)))
  envelope <- list(
    app = "CardinalNEST",
    kind = "preprocessing_workflow",
    version = 1L,
    created = format(Sys.time(), "%Y-%m-%dT%H:%M:%S"),
    name = if (is.null(name) || !nzchar(name)) "workflow" else name,
    steps = steps
  )
  jsonlite::toJSON(envelope, auto_unbox = TRUE, pretty = TRUE, null = "null")
}

# Parse workflow JSON (string or file path) back to validated specs.
deserialize_workflow <- function(json) {
  if (length(json) == 1L && !grepl("[{\\[]", json) && file.exists(json)) {
    json <- paste(readLines(json, warn = FALSE), collapse = "\n")
  }
  obj <- jsonlite::fromJSON(json, simplifyVector = FALSE)
  if (is.null(obj$kind) || !identical(obj$kind, "preprocessing_workflow")) {
    stop("Not a Cardinal NEST preprocessing workflow file.", call. = FALSE)
  }
  steps <- obj$steps
  if (is.null(steps)) steps <- list()
  specs <- lapply(steps, function(s) {
    args <- s$args
    if (is.null(args)) args <- list()
    # simplifyVector = FALSE yields lists; unlist each arg back to a vector.
    args <- lapply(args, function(v) if (is.list(v)) unlist(v, use.names = FALSE) else v)
    list(type = s$type, args = args)
  })
  validate_workflow_specs(specs)
}

# e.g. list(method = "tic", width = 11) -> 'method = "tic", width = 11'
format_r_args <- function(args) {
  if (length(args) == 0L) return("")
  nms <- names(args)
  parts <- vapply(seq_along(args), function(i) {
    sprintf("%s = %s", nms[i], paste(deparse(args[[i]]), collapse = ""))
  }, character(1))
  paste(parts, collapse = ", ")
}

# Generate a headless R script that reruns the workflow outside the app.
workflow_to_rscript <- function(specs,
                                input_path = "path/to/data.imzML",
                                output_path = "preprocessed.rds") {
  specs <- validate_workflow_specs(specs)
  lines <- c(
    "# Auto-generated by Cardinal NEST - reproducible preprocessing workflow",
    "# Edit the input/output paths below, then run with:",
    "#   Rscript this_script.R",
    "",
    "library(Cardinal)",
    "",
    sprintf("data <- readMSIData(%s)", deparse(input_path)),
    ""
  )
  for (i in seq_along(specs)) {
    s <- specs[[i]]
    def <- preproc_step_defs[[s$type]]
    if (identical(s$type, "peakFilter")) {
      lines <- c(lines,
                 sprintf("# Step %d (%s): peakFilter is deprecated - skipped",
                         i, def$label))
      next
    }
    args_str <- format_r_args(s$args)
    call_str <- if (nzchar(args_str)) {
      sprintf("data <- %s(data, %s)", def$fn, args_str)
    } else {
      sprintf("data <- %s(data)", def$fn)
    }
    lines <- c(lines, sprintf("# Step %d: %s", i, def$label), call_str, "")
  }
  lines <- c(lines,
             "# Flush any queued transformations",
             "data <- process(data)",
             "",
             sprintf("saveRDS(data, %s)", deparse(output_path)))
  paste(lines, collapse = "\n")
}

# Run `specs` over `ids`, one new record per input; `progress` is an
# optional function(fraction, detail). Returns list(records, status).
run_batch_preprocessing <- function(datasets, ids, specs, progress = NULL) {
  specs <- validate_workflow_specs(specs)
  if (length(specs) == 0L) {
    stop("Workflow has no steps to run.", call. = FALSE)
  }
  if (length(ids) == 0L) {
    stop("No datasets selected for batch preprocessing.", call. = FALSE)
  }
  step_labels <- vapply(specs, function(s) preproc_step_defs[[s$type]]$label,
                        character(1))

  new_records <- list()
  status <- data.frame(
    id = character(0), name = character(0), status = character(0),
    new_id = character(0), detail = character(0),
    stringsAsFactors = FALSE
  )

  n <- length(ids)
  for (k in seq_len(n)) {
    id <- ids[k]
    rec <- datasets[[id]]
    nm <- if (!is.null(rec)) rec$name else id
    if (!is.null(progress)) {
      progress(k / n, sprintf("(%d/%d) %s", k, n, nm))
    }

    if (is.null(rec) || is.null(rec$data)) {
      status <- rbind(status, data.frame(
        id = id, name = nm, status = "failed", new_id = NA_character_,
        detail = "Dataset not found or has no data.",
        stringsAsFactors = FALSE))
      next
    }

    run <- tryCatch(run_preproc_pipeline(rec$data, specs),
                    error = function(e) e)
    if (inherits(run, "error")) {
      status <- rbind(status, data.frame(
        id = id, name = nm, status = "failed", new_id = NA_character_,
        detail = conditionMessage(run), stringsAsFactors = FALSE))
      next
    }

    new_id <- next_dataset_id(c(names(datasets), names(new_records)))
    new_name <- paste0(nm, " [wf]")
    record <- make_preproc_record(run$data, new_id, step_labels,
                                  filename = new_name)
    new_records[[new_id]] <- record

    detail <- sprintf("%d step(s)", length(specs))
    if (length(run$warnings) > 0) {
      detail <- paste0(detail, "; warnings: ",
                       paste(run$warnings, collapse = "; "))
    }
    status <- rbind(status, data.frame(
      id = id, name = nm, status = "success", new_id = new_id,
      detail = detail, stringsAsFactors = FALSE))
  }

  list(records = new_records, status = status)
}

# Human-readable one-line-per-step summary of a workflow, used in the UI.
workflow_summary_lines <- function(specs) {
  specs <- validate_workflow_specs(specs)
  if (length(specs) == 0L) return(character(0))
  vapply(seq_along(specs), function(i) {
    s <- specs[[i]]
    def <- preproc_step_defs[[s$type]]
    args_str <- format_r_args(s$args)
    if (nzchar(args_str)) {
      sprintf("%d. %s (%s)", i, def$label, args_str)
    } else {
      sprintf("%d. %s", i, def$label)
    }
  }, character(1))
}

