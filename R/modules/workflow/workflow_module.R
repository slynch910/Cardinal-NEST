             p(paste("Reuse a preprocessing pipeline as a saveable workflow, export",
                     "it as a reproducible R script, and apply it across many",
                     "datasets at once."))
      )
    ),
    fluidRow(
      column(5,
             bslib::card(
               bslib::card_header("Workflow definition"),
               bslib::card_body(
                 radioButtons(ns("wf_source"), "Workflow source",
                              choices = c("Current Preprocess pipeline" = "current",
                                          "Loaded from file" = "loaded"),
                              selected = "current"),
                 conditionalPanel(
                   condition = sprintf("input['%s'] == 'loaded'", ns("wf_source")),
                   fileInput(ns("wf_file"), "Load workflow (.json)",
                             accept = c(".json", "application/json"))
                 ),
                 tags$label("Steps"),
                 verbatimTextOutput(ns("wf_steps")),
                 textInput(ns("wf_name"), "Workflow name", value = "workflow"),
                 div(class = "d-flex gap-2 flex-wrap",
                     downloadButton(ns("wf_save"), "Save workflow (.json)",
                                    class = "btn-outline-primary btn-sm"),
                     downloadButton(ns("wf_script"), "Export R script (.R)",
                                    class = "btn-outline-secondary btn-sm")
                 )
               )
             )
      ),
      column(7,
             bslib::card(
               bslib::card_header("Batch preprocessing"),
               bslib::card_body(
                 uiOutput(ns("dataset_picker")),
                 actionButton(ns("run_batch"), "Run workflow on selected datasets",
                              icon = icon("play"), class = "btn-primary"),
                 uiOutput(ns("batch_status")),
                 tableOutput(ns("batch_results"))
               )
             )
      )
    )
  )
}

# `preproc_specs`: reactive returning the current Preprocess pipeline specs.
workflowServer <- function(id, datasets, active_id, preproc_specs = reactive(list())) {
  moduleServer(id, function(input, output, session) {
    ns <- session$ns

    loaded_specs <- reactiveVal(list())
    batch_status <- reactiveVal(list(type = "info",
                                     message = "No batch run yet."))
    batch_results <- reactiveVal(NULL)

    observeEvent(input$wf_file, {
      req(input$wf_file)
      specs <- tryCatch(
        deserialize_workflow(input$wf_file$datapath),
        error = function(e) {
          batch_status(list(type = "danger",
                            message = paste("Failed to load workflow:",
                                            conditionMessage(e))))
          NULL
        }
      )
      if (!is.null(specs)) {
        loaded_specs(specs)
        batch_status(list(type = "success",
                          message = sprintf("Loaded workflow with %d step(s).",
                                            length(specs))))
      }
    })

    # Workflow in effect per the selected source.
    active_specs <- reactive({
      if (identical(input$wf_source, "loaded")) {
        loaded_specs()
      } else {
        tryCatch(preproc_specs(), error = function(e) list())
      }
    })

    output$wf_steps <- renderText({
      lines <- tryCatch(workflow_summary_lines(active_specs()),
                        error = function(e) character(0))
      if (length(lines) == 0) {
        "(empty - build a pipeline in the Preprocess tab or load one from file)"
      } else {
        paste(lines, collapse = "\n")
      }
    })

    output$dataset_picker <- renderUI({
      ds <- datasets()
      if (length(ds) == 0) {
        return(div(class = "alert alert-warning",
                   "No datasets available. Import data first."))
      }
      choices <- setNames(names(ds), vapply(ds, function(r) r$name, character(1)))
      checkboxGroupInput(ns("batch_ids"), "Datasets to process",
                         choices = choices, selected = names(ds))
    })

    output$wf_save <- downloadHandler(
      filename = function() {
        nm <- input$wf_name
        if (is.null(nm) || !nzchar(nm)) nm <- "workflow"
        paste0(gsub("[^A-Za-z0-9_-]+", "_", nm), ".json")
      },
      content = function(file) {
        writeLines(serialize_workflow(active_specs(), name = input$wf_name), file)
      }
    )

    output$wf_script <- downloadHandler(
      filename = function() {
        nm <- input$wf_name
        if (is.null(nm) || !nzchar(nm)) nm <- "workflow"
        paste0(gsub("[^A-Za-z0-9_-]+", "_", nm), ".R")
      },
      content = function(file) {
        writeLines(workflow_to_rscript(active_specs()), file)
      }
    )

    observeEvent(input$run_batch, {
      specs <- active_specs()
      ids <- input$batch_ids
      if (length(specs) == 0) {
        batch_status(list(type = "warning",
                          message = "The selected workflow has no steps."))
        return()
      }
      if (length(ids) == 0) {
        batch_status(list(type = "warning",
                          message = "Select at least one dataset."))
        return()
      }

      res <- tryCatch(
        withProgress(message = "Running workflow", value = 0, {
          run_batch_preprocessing(
            datasets(), ids, specs,
            progress = function(frac, detail) {
              setProgress(value = frac, detail = detail)
            })
        }),
        error = function(e) {
          batch_status(list(type = "danger", message = conditionMessage(e)))
          NULL
        }
      )
      if (is.null(res)) return()

      if (length(res$records) > 0) {
        ds <- datasets()
        for (nid in names(res$records)) ds[[nid]] <- res$records[[nid]]
        datasets(ds)
        active_id(names(res$records)[[length(res$records)]])
      }

      batch_results(res$status)
      n_ok <- sum(res$status$status == "success")
      n_fail <- sum(res$status$status == "failed")
      type <- if (n_fail == 0) "success" else if (n_ok == 0) "danger" else "warning"
      batch_status(list(
        type = type,
        message = sprintf("Batch complete: %d succeeded, %d failed. New datasets added to the store.",
                          n_ok, n_fail)))
    })

    output$batch_status <- renderUI(status_alert(batch_status(), extra_class = "mt-3"))

    output$batch_results <- renderTable({
      res <- batch_results()
      if (is.null(res) || nrow(res) == 0) return(NULL)
      data.frame(
        Dataset = res$name,
        Status = res$status,
        `New dataset` = ifelse(is.na(res$new_id), "", res$new_id),
        Detail = res$detail,
        check.names = FALSE,
        stringsAsFactors = FALSE
      )
    })
  })
}
